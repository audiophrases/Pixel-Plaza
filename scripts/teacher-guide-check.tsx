import { JSDOM } from 'jsdom';
import assert from 'node:assert/strict';
import { castanyada, castanyadaInvestigations } from '../shared/campaign';
import { buildGuide, type TeacherGuide } from '../shared/teacherGuide';

const dom = new JSDOM('<!doctype html><div id="root"></div>', { url: 'http://localhost/teacher', pretendToBeVisual: true });
Object.assign(globalThis, { window: dom.window, document: dom.window.document, HTMLElement: dom.window.HTMLElement, IS_REACT_ACT_ENVIRONMENT: true });
Object.defineProperty(globalThis, 'navigator', { value: dom.window.navigator, configurable: true });
const { createRoot } = await import('react-dom/client');
const { act } = await import('react');
const { default: TeacherMissionGuide } = await import('../src/components/TeacherMissionGuide');
const root = createRoot(document.getElementById('root')!);
const preview: TeacherGuide = { campaign: { id: castanyada.id, title: castanyada.title, revision: 'v1' }, game: null, currentChapter: 0, ...buildGuide(castanyada) };
const live: TeacherGuide = { campaign: { id: castanyadaInvestigations.id, title: castanyadaInvestigations.title, revision: 'v1' }, game: { id: 'game-a', name: 'Class A' }, currentChapter: 1,
  ...buildGuide(castanyadaInvestigations, { thiefNames: [[], ['Brave Owl']] }) };
let reply = preview, calls: string[] = [], fail = false;
let delayed: ((response: Response) => void) | undefined;
globalThis.fetch = async (url, init) => {
  calls.push(String(url));
  assert.equal((init?.headers as Record<string, string> | undefined)?.['x-teacher-session'], 'teacher-session');
  if (String(url).includes('game=slow')) return new Promise<Response>(resolve => { delayed = resolve; });
  return fail ? Response.json({ error: 'Guide unavailable.' }, { status: 503 }) : Response.json(reply);
};
const settle = async () => { await new Promise(resolve => setTimeout(resolve, 10)); };
const render = async (props: object) => act(async () => { root.render(<TeacherMissionGuide token="teacher-session" {...props} />); await settle(); });
await render({ campaignId: castanyada.id });
assert.equal(calls.length, 0, 'preview guides do not load until opened');
await act(async () => { const details = document.querySelector('details')!; details.open = true; details.dispatchEvent(new dom.window.Event('toggle')); await settle(); });
assert.equal(calls.length, 1);
assert.ok(document.body.textContent?.includes('park / pond'));
assert.equal(document.querySelectorAll('.mission-guide-tag').length, 0, 'the basic campaign has no witness requirement');
assert.equal(document.querySelectorAll('select option').length, 3);
reply = structuredClone(preview); reply.campaign.revision = 'v2'; reply.chapters[0].main[0].answer = 'cafe';
await render({ campaignId: castanyada.id, refreshKey: 'v2' });
assert.equal(document.querySelector('.mission-guide-answer')?.textContent, 'cafe', 'an open preview refreshes after a new publication');
reply = live;
await render({ gameId: 'game-a', currentChapter: 1, refreshKey: 'first' });
assert.equal((document.querySelector('select') as HTMLSelectElement).value, '1');
assert.ok(document.body.textContent?.includes('Brave Owl'));
assert.ok([...document.querySelectorAll('.mission-guide-tag')].some(el => el.textContent === '2 witnesses'));
assert.equal(document.querySelectorAll('select option').length, 5);
assert.ok(document.body.textContent?.includes('Approve the question'));
assert.ok(document.body.textContent?.includes('Approve the reply'));
await act(async () => { const select = document.querySelector('select')!; select.value = '3'; select.dispatchEvent(new dom.window.Event('change', { bubbles: true })); });
assert.ok(document.querySelector('h4')?.textContent?.includes('Festival Plan'));
await render({ gameId: 'game-a', currentChapter: 1, refreshKey: 'live-addition' });
assert.equal((document.querySelector('select') as HTMLSelectElement).value, '3', 'refresh does not interrupt browsing another chapter');
await render({ gameId: 'game-a', currentChapter: 2, refreshKey: 'advanced' });
assert.equal((document.querySelector('select') as HTMLSelectElement).value, '2', 'advancing the game selects the new chapter');
assert.ok(document.body.textContent?.includes('7431'));
// A late response from a different game must never replace the current guide.
await render({ gameId: 'slow', currentChapter: 0 });
await render({ gameId: 'game-a', currentChapter: 1 });
await act(async () => { delayed?.(Response.json({ ...preview, game: { id: 'slow', name: 'Other class' } })); await settle(); });
assert.ok(document.body.textContent?.includes('Brave Owl'));
fail = true;
await render({ gameId: 'game-a', currentChapter: 1, refreshKey: 'failure' });
assert.ok(document.querySelector('[role="alert"]')?.textContent?.includes('Guide unavailable'));
fail = false;
await act(async () => { (document.querySelector('[role="alert"] button') as HTMLButtonElement).click(); await settle(); });
assert.ok(document.body.textContent?.includes('Brave Owl'));
await act(async () => { root.unmount(); });
dom.window.close();
console.log('Teacher guide UI: lazy preview, 3/5 chapters, witnesses, answers, chapter changes, freshness, race handling and retry pass.');
process.exit(0);
